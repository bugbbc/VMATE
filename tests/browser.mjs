import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

const baseURL = process.env.TEST_BASE_URL || 'http://127.0.0.1:8787';
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(baseURL)) throw new Error('Run these tests against a local development server only.');
const artifactDir = path.resolve(process.env.ARTIFACT_DIR || '../outputs');
await mkdir(artifactDir, { recursive: true });
const browser = await chromium.launch({
  ...(process.env.TEST_BROWSER_CHANNEL === 'chromium' ? {} : { channel: process.env.TEST_BROWSER_CHANNEL || 'chrome' }),
  headless: true,
});
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const username = `qa_${Date.now()}`;
let storyId;
try {
  await page.goto(`${baseURL}/community.html`);
  await expect(page.locator('#feed')).toHaveAttribute('aria-busy', 'false');
  await expect(page.getByRole('heading', { name: /Every drive/ })).toBeVisible();
  await page.screenshot({ path: path.join(artifactDir, 'community-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Share your story' }).click();
  await expect(page.locator('#auth-dialog')).toBeVisible();
  await page.getByLabel('Display name', { exact: true }).fill('QA test member');
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Password', { exact: true }).fill('Community-test-password-2026!');
  await page.locator('#auth-submit').click();
  await expect(page.locator('#compose-dialog')).toBeVisible();
  await page.getByLabel('Fragrance', { exact: true }).selectOption('white-tea');
  await page.getByLabel('Conversation', { exact: true }).selectOption('photos');
  await page.getByLabel('Give your story a title').fill('QA test — a fresh morning drive');
  await page.getByLabel('Your experience', { exact: true }).fill('A browser test of photos, emoji and replies. <img src=x onerror="window.xss=true">');
  await page.getByRole('button', { name: 'Add emoji' }).click();
  await page.getByRole('button', { name: 'Insert 🌿', exact: true }).click();
  await expect(page.locator('#post-body')).toHaveValue(/🌿/);
  await page.locator('#photo-input').setInputFiles(['assets/astrum/main/main-02.jpg', 'assets/astrum/main/main-03.jpg']);
  await expect(page.locator('.photo-preview')).toHaveCount(2, { timeout: 15000 });
  await expect(page.locator('#post-submit')).toBeEnabled();
  await page.getByRole('button', { name: 'Remove photo 2' }).click();
  await expect(page.locator('.photo-preview')).toHaveCount(1);
  await page.getByLabel('Your rating', { exact: false }).selectOption('5');
  await page.locator('#post-submit').click();
  await expect(page.locator('#compose-dialog')).not.toBeVisible({ timeout: 15000 });
  await expect(page.locator('.post-card')).toHaveCount(1);
  storyId = new URL(page.url()).searchParams.get('post');
  if (!storyId) throw new Error('Published story has no permalink');
  await expect(page.locator('.post-body')).toContainText('<img src=x onerror="window.xss=true">');
  expect(await page.evaluate(() => window.xss)).toBeUndefined();
  await expect(page.locator('.post-body img')).toHaveCount(0);
  await page.getByRole('button', { name: /View photo 1/ }).click();
  await expect(page.locator('#lightbox')).toBeVisible();
  await expect.poll(() => page.locator('#lightbox-image').evaluate(image => image.complete && image.naturalWidth > 0)).toBe(true);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Love this story' }).click();
  await expect(page.getByRole('button', { name: 'Love this story' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: '0 replies', exact: true }).click();
  await page.getByLabel('Keep the conversation going').fill('A reply with emoji 😍 中文测试');
  await page.getByRole('button', { name: 'Post reply', exact: true }).click();
  await expect(page.locator('.comment')).toContainText('中文测试');
  await page.reload();
  await expect(page.locator('.post-card')).toHaveCount(1);
  await expect(page.getByRole('button', { name: '1 replies', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Love this story' })).toHaveAttribute('aria-pressed', 'true');

  const visitor = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mobile = await visitor.newPage();
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(`${baseURL}/community.html?post=${storyId}`);
  await expect(mobile.locator('.post-card')).toHaveCount(1);
  await expect(mobile.locator('.post-photos img')).toHaveCount(1);
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(mobile.locator('.post-actions').getByRole('button', { name: 'Delete', exact: true })).toHaveCount(0);
  await mobile.getByRole('button', { name: '1 replies', exact: true }).click();
  await expect(mobile.locator('.comment')).toContainText('中文测试');
  await mobile.getByRole('button', { name: 'Sign in to reply' }).click();
  await expect(mobile.locator('#auth-dialog')).toBeVisible();
  await mobile.keyboard.press('Escape');
  await mobile.goto(`${baseURL}/community.html`);
  await expect(mobile.locator('#feed')).toHaveAttribute('aria-busy', 'false');
  await mobile.locator('#product-filter').selectOption('lavender');
  await expect(mobile.locator('#result-count')).toHaveText('0');
  await expect(mobile.getByRole('button', { name: 'Clear filters' })).toBeVisible();
  await mobile.getByRole('button', { name: 'Clear filters' }).click();
  await expect(mobile.locator('.post-card')).toHaveCount(1);
  await mobile.route('**/api/posts?**', route => route.abort());
  await mobile.reload();
  await expect(mobile.getByRole('button', { name: 'Try again' })).toBeVisible();
  await mobile.unroute('**/api/posts?**');
  await mobile.getByRole('button', { name: 'Try again' }).click();
  await expect(mobile.locator('.post-card')).toHaveCount(1);
  await visitor.close();

  await page.locator('.post-actions').getByRole('button', { name: 'Delete', exact: true }).click();
  await page.locator('#confirm-action').click();
  await expect(page.locator('.post-card')).toHaveCount(0);
  storyId = null;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${baseURL}/community.html`);
  await expect(page.locator('#feed')).toHaveAttribute('aria-busy', 'false');
  await page.screenshot({ path: path.join(artifactDir, 'community-mobile.png'), fullPage: true });
  await page.goto(`${baseURL}/index.html`);
  await expect(page.locator('.community-nav-link')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.locator('.community-nav-link').click();
  await expect(page.getByRole('heading', { name: /Every drive/ })).toBeVisible();
  await page.goto(`${baseURL}/astrum-detail.html?variant=lavender`);
  await expect(page.locator('#communityLink')).toHaveAttribute('href', 'community.html?product=lavender');
  await page.locator('#communityLink').click();
  await expect(page.locator('#product-filter')).toHaveValue('lavender');
  expect(errors).toEqual([]);
  console.log('PASS: registration, upload/previews, emoji, publish, lightbox, likes, replies, refresh, independent visitor, filters, retry, deletion, navigation, mobile overflow and script injection.');
} finally {
  if (storyId) await context.request.delete(`${baseURL}/api/posts/${storyId}`, { headers: { 'X-VMATE-Request': '1' } }).catch(() => {});
  await browser.close();
}
